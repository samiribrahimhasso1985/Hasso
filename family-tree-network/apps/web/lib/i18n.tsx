export const DICTS: Record<Locale, Dict> = { en, de, ar, ku };
export const dirOf = (l: Locale): 'rtl' | 'ltr' => (l === 'ar' ? 'rtl' : 'ltr');

interface I18n {
  locale: Locale;
  dir: 'rtl' | 'ltr';
  t: Dict;
  setLocale: (l: Locale) => void;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children, initial = 'ar' }: { children: ReactNode; initial?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(initial);
  useEffect(() => {
    try {
      const saved = localStorage.getItem('ftn.locale') as Locale | null;
      if (saved && DICTS[saved]) setLocaleState(saved);
    } catch {
      /* storage unavailable: keep default */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = dirOf(locale);
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem('ftn.locale', l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo(() => ({ locale, dir: dirOf(locale), t: DICTS[locale], setLocale }), [locale, setLocale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
