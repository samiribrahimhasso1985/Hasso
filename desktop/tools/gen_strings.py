"""Generate Localization/Strings.<lang>.xaml from tools/strings.py."""
from pathlib import Path
from xml.sax.saxutils import escape
import sys

sys.path.insert(0, str(Path(__file__).parent))
from strings import S  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "src" / "Discoveries.Desktop" / "Localization"
LANGS = {"ar": 0, "en": 1, "de": 2}

for lang, idx in LANGS.items():
    lines = [
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:sys="clr-namespace:System;assembly=mscorlib">',
        "    <!-- GENERATED by tools/gen_strings.py — edit tools/strings.py instead. -->",
    ]
    for key, values in S.items():
        lines.append(f'    <sys:String x:Key="{key}">{escape(values[idx])}</sys:String>')
    lines.append("</ResourceDictionary>")
    (OUT / f"Strings.{lang}.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(S)} keys x {len(LANGS)} languages")
